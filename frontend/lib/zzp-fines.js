/**
 * Къде в диапазона [min, max] попада оценката според тежестта на нарушението.
 * Ориентирът е средата (0.5); тежестта само го измества в рамките 40% - 60%.
 */
const POSITION_BY_SCORE = { 1: 0.60, 2: 0.50, 3: 0.40 };
const EXTRA_PER_ADDITIONAL_CRITERION = 0.04; // всяко следващо засегнато изискване в същата разпоредба
const MAX_POSITION = 0.70;
const ROUND_TO = 50; // евро

const roundTo = (n, step) => Math.round(n / step) * step;

/**
 * @param {Array} criteria  плосък масив на критериите от T&C (id, name, score, skipped)
 * @returns {{ rows: Array, totalMin: number, totalMax: number, totalEstimate: number }}
 */
export function estimateFines(criteria = []) {
  const byArticle = {};

  for (const c of criteria) {
    if (c.skipped || c.score == null || c.score >= 4) continue;
    for (const key of CRITERION_ARTICLES[c.id] ?? []) {
      const art = FINE_ARTICLES[key];
      if (!art?.enabled) continue;
      (byArticle[key] ??= []).push(c);
    }
  }

  const rows = Object.entries(byArticle).map(([key, hits]) => {
    const art    = FINE_ARTICLES[key];
    const worst  = Math.min(...hits.map(h => h.score));
    const pos    = Math.min(
      MAX_POSITION,
      (POSITION_BY_SCORE[worst] ?? 0.5) + EXTRA_PER_ADDITIONAL_CRITERION * (hits.length - 1),
    );
    const estimate = roundTo(art.min + (art.max - art.min) * pos, ROUND_TO);
    const consequences = hits
      .filter(h => h.score <= 2 && CRITERION_CONSEQUENCES[h.id])
      .map(h => CRITERION_CONSEQUENCES[h.id]);
    return {
      key, ...art, hits, estimate, consequences,
      worstScore: worst,
    };
  }).sort((a, b) => b.estimate - a.estimate);

  return {
    rows,
    totalMin:      rows.reduce((s, r) => s + r.min, 0),
    totalMax:      rows.reduce((s, r) => s + r.max, 0),
    totalEstimate: rows.reduce((s, r) => s + r.estimate, 0),
  };
}

